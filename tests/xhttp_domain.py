#!/usr/bin/env python3
"""Check managed Reality domain reuse, certificate retention and rollback."""
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

REPO = Path(__file__).resolve().parents[1]
MARKER = '# Generated by singbox-lite Reality local origin'
DOMAIN = 'storage.example.com'

HARNESS = r'''
source "$REPO/sb.sh"
SINGBOX_DIR="$WORK"
CONFIG_FILE="$WORK/config.json"
METADATA_FILE="$WORK/metadata.json"
CLASH_YAML_FILE="$WORK/clash.yaml"
XRAY_CONFIG_FILE="$WORK/xray.json"
NGINX_CONF_DIR="$WORK/conf.d"
NGINX_CERT_DIR="$WORK/certs"
NGINX_BACKUP_DIR="$WORK/backup"
SNI_ROUTER_STATE_FILE="$WORK/router.json"
SNI_ROUTER_HAPROXY_CONF="$WORK/haproxy.cfg"
NFT_PERSIST_FILE="$WORK/nft.rules"
NODE_NFT_CONFIG_FILE="$WORK/nft.conf"
PROXYALL_WRITE_LOCK_FILE="$WORK/write.lock"
INIT_SYSTEM=direct
PID_FILE="$WORK/singbox.pid"
_xray_running() { return 1; }
_node_tx_validate() { return 0; }
_manage_service() { return 0; }
_sb_reload_or_start_nginx() { echo reload >> "$WORK/reloads"; [ "${FAIL_NGINX:-0}" != 1 ]; }
nginx() {
    [ "$1" = -T ] || return 1
    local file
    for file in "$NGINX_CONF_DIR/"*.conf; do
        [ -f "$file" ] || continue
        printf '# configuration file %s:\n' "$file"
        cat "$file"
    done
}
_install_sb_acme() { echo unexpected-acme >&2; return 1; }
_validate_local_origin_dns() { echo unexpected-dns >&2; return 1; }
run() {
    _node_tx_begin || return 1
    _xhttp_prepare_domain storage.example.com || return 1
    [ "${CHECK_CERT:-0}" != 1 ] || _xhttp_prepare_certificate storage.example.com || return 1
    [ "${FAIL_AFTER:-0}" != 1 ]
}
_node_operation run
'''


class DomainReuseTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='proxyall-domain-test-')
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        (self.root / 'conf.d').mkdir()
        for name in ('config.json', 'relay.json'):
            self.write_json(name, {'inbounds': [], 'outbounds': []})
        for name in ('metadata.json', 'relay_links.json'):
            self.write_json(name, {})
        (self.root / 'clash.yaml').write_text('proxies: []\n')
        (self.root / 'harness.sh').write_text(HARNESS)
        self.origin = self.conf(f'{DOMAIN}.8443.reality.conf', MARKER, '127.0.0.1:8443 ssl')
        self.challenge = self.conf(f'00-sb-reality-acme-{DOMAIN}.conf', MARKER, '80')

    def write_json(self, name, value):
        (self.root / name).write_text(json.dumps(value))

    def conf(self, name, marker, listen):
        path = self.root / 'conf.d' / name
        path.write_text(f'{marker}\nserver {{\n    listen {listen};\n    server_name {DOMAIN};\n}}\n')
        return path

    def run_case(self, expected=0, **extra):
        result = subprocess.run(['bash', str(self.root / 'harness.sh')],
                                env=dict(os.environ, REPO=str(REPO), WORK=str(self.root), **extra),
                                capture_output=True, text=True, timeout=10)
        if expected == 0:
            self.assertEqual(result.returncode, 0, result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0, result.stderr)
        return result

    def active_reality(self):
        return {'type': 'vless', 'tag': 'active', 'tls': {'server_name': DOMAIN,
                'reality': {'enabled': True, 'handshake': {'server': '127.0.0.1', 'server_port': 8443}}}}

    def test_unused_origin_retires_but_renewal_remains(self):
        original = self.origin.read_bytes()
        challenge = self.challenge.read_bytes()
        self.run_case()
        self.assertFalse(self.origin.exists())
        self.assertEqual(self.challenge.read_bytes(), challenge)
        backup = list((self.root / 'backup').iterdir())
        self.assertEqual(len(backup), 1)
        self.assertEqual(backup[0].read_bytes(), original)

    def test_active_main_reality_is_preserved(self):
        self.write_json('config.json', {'inbounds': [self.active_reality()]})
        self.run_case(expected=1)
        self.assertTrue(self.origin.exists())
        self.assertFalse((self.root / 'reloads').exists())

    def test_active_relay_reality_is_preserved(self):
        self.write_json('relay.json', {'inbounds': [self.active_reality()]})
        self.run_case(expected=1)
        self.assertTrue(self.origin.exists())

    def test_broken_relay_aborts_without_changes(self):
        (self.root / 'relay.json').write_text('{broken')
        self.run_case(expected=1)
        self.assertTrue(self.origin.exists())

    def test_unmanaged_origin_is_preserved(self):
        self.origin.write_text(self.origin.read_text().replace(MARKER, '# custom site'))
        self.run_case(expected=1)
        self.assertTrue(self.origin.exists())

    def test_unmanaged_challenge_blocks_reuse(self):
        self.challenge.write_text(self.challenge.read_text().replace(MARKER, '# custom site'))
        self.run_case(expected=1)
        self.assertTrue(self.origin.exists())

    def test_other_site_blocks_reuse_without_removing_origin(self):
        other = self.conf('website.conf', '# website', '443 ssl')
        before = other.read_bytes()
        self.run_case(expected=1)
        self.assertTrue(self.origin.exists())
        self.assertEqual(other.read_bytes(), before)

    def test_later_failure_restores_origin(self):
        before = self.origin.read_bytes()
        self.run_case(expected=1, FAIL_AFTER='1')
        self.assertEqual(self.origin.read_bytes(), before)
        self.assertTrue(self.challenge.exists())

    def test_nginx_failure_restores_origin(self):
        before = self.origin.read_bytes()
        self.run_case(expected=1, FAIL_NGINX='1')
        self.assertEqual(self.origin.read_bytes(), before)

    def test_challenge_alone_allows_reuse(self):
        self.origin.unlink()
        self.run_case()
        self.assertTrue(self.challenge.exists())

    def test_valid_certificate_is_reused_without_acme(self):
        certdir = self.root / 'certs' / DOMAIN
        certdir.mkdir(parents=True)
        subprocess.run(['openssl', 'req', '-x509', '-newkey', 'ec', '-pkeyopt', 'ec_paramgen_curve:P-256',
                        '-nodes', '-keyout', str(certdir / 'key'), '-out', str(certdir / 'cert'),
                        '-subj', f'/CN={DOMAIN}', '-addext', f'subjectAltName=DNS:{DOMAIN}', '-days', '73'],
                       check=True, capture_output=True)
        before = {name: (certdir / name).read_bytes() for name in ('cert', 'key')}
        self.run_case(CHECK_CERT='1')
        self.assertEqual(before, {name: (certdir / name).read_bytes() for name in ('cert', 'key')})
        self.assertTrue(self.challenge.exists())


if __name__ == '__main__':
    unittest.main(verbosity=2)
